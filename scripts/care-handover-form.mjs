const plantCard = (t, n) =>
  `<fieldset class="handover-plant"><legend>${t.plant} ${n}</legend><div class="handover-grid"><label>${t.name}<input type="text" name="plant-${n}-name" autocomplete="off"></label><label>${t.room}<input type="text" name="plant-${n}-room" autocomplete="off"></label><label>${t.lastCheck}<input type="date" name="plant-${n}-last-check"></label><label>${t.lastWater}<input type="date" name="plant-${n}-last-watering"></label></div><label>${t.conditions}<span class="handover-hint">${t.conditionsHint}</span><textarea name="plant-${n}-conditions" rows="2"></textarea></label><label>${t.notes}<span class="handover-hint">${t.notesHint}</span><textarea name="plant-${n}-notes" rows="3"></textarea></label></fieldset>`;

export const handoverFormTitle = (lang) => (copy[lang] || copy.en).title;

export function careHandoverForm(lang) {
  const t = copy[lang] || copy.en;
  const plants = [1, 2, 3].map((n) => plantCard(t, n)).join("");
  return `<section id="handover-form" class="handover-form" aria-labelledby="handover-form-title"><p class="eyebrow">${t.eyebrow}</p><h2 id="handover-form-title">${t.title}</h2><p>${t.intro}</p><p class="handover-privacy">${t.privacy}</p><form data-handover-form data-plant-label="${t.plant}" autocomplete="off"><fieldset class="handover-general"><legend>${t.general}</legend><div class="handover-grid"><label>${t.away}<input type="text" name="away-dates"></label><label>${t.carer}<input type="text" name="carer"></label></div><label>${t.contact}<input type="text" name="contact"></label></fieldset><div data-handover-plants>${plants}</div><div class="handover-actions" hidden><button type="button" data-handover-add>${t.add}</button><button type="button" data-handover-print>${t.print}</button></div></form><p class="handover-footer">${t.footer}</p><script defer src="/assets/handover-form.js"></script></section>`;
}
